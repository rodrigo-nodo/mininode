def test_startup_failure_is_logged_without_breaking_health(monkeypatch, caplog):
    monkeypatch.delenv("DATABASE_URL", raising=False)
    app = create_app()
    with caplog.at_level("ERROR"), TestClient(app) as startup_client:
        assert startup_client.get("/health").status_code == 200
        assert startup_client.post(
            "/learn/feedback",
            json={"content_key": learn_feedback.CONTENT_KEY, "rating": 3},
        ).status_code == 503
    assert "Learn feedback database initialization failed" in caplog.text
    assert "postgres" not in caplog.text.lower()
