def test_initialization_uses_idempotent_learn_schema_and_seed(monkeypatch):
    executions = []

    class Cursor:
        def execute(self, statement, params=None):
            executions.append((statement, params))

        def __enter__(self):
            return self

        def __exit__(self, *args):
            pass

    class Connection:
        def cursor(self):
            return Cursor()

    @contextmanager
    def connection():
        yield Connection()

    monkeypatch.setattr(learn_feedback, "_connection", connection)
    learn_feedback.initialize_database()
    learn_feedback.initialize_database()

    assert len(executions) == 2
    sql = executions[0][0]
    assert "CREATE SCHEMA IF NOT EXISTS learn" in sql
    assert "CREATE TABLE IF NOT EXISTS learn.content" in sql
    assert "CREATE TABLE IF NOT EXISTS learn.feedback" in sql
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "content_key TEXT UNIQUE NOT NULL" in sql
    assert "slug TEXT UNIQUE NOT NULL" in sql
    assert "REFERENCES learn.content(id)" in sql
    assert "ON CONFLICT (content_key) DO NOTHING" in sql
    assert learn_feedback.BRIEF_001_CONTENT_KEY in sql
    assert learn_feedback.BRIEF_003_CONTENT_KEY in sql
    assert "'/learn/briefs/001-nueva-autoridad-de-datos'" in sql
    assert "'/learn/briefs/003-datos-personales'" in sql
    assert "'brief'" in sql
    assert "CREATE INDEX IF NOT EXISTS learn_feedback_content_id_idx" in sql
    assert "public.learn_" not in sql


def test_create_feedback_snapshots_content_identity_and_version(monkeypatch):
    feedback_id = uuid4()
    statements = []

    class Cursor:
        def execute(self, statement, params=None):
            statements.append((" ".join(statement.split()), params))

        def fetchone(self):
            return (41, 3)

        def __enter__(self):
            return self

        def __exit__(self, *args):
            pass

    @contextmanager
    def connection():
        yield type("Connection", (), {"cursor": lambda self: Cursor()})()

    monkeypatch.setattr(learn_feedback, "_connection", connection)
    monkeypatch.setattr(learn_feedback, "uuid4", lambda: feedback_id)

    result = learn_feedback.create_feedback(content_key=learn_feedback.CONTENT_KEY, rating=4)

    assert result == feedback_id
    assert statements[0][1] == (learn_feedback.CONTENT_KEY,)
    assert "FROM learn.content" in statements[0][0]
    assert statements[1][1] == (feedback_id, 41, 3, 4)
    assert "INSERT INTO learn.feedback" in statements[1][0]
    assert "content_key" not in statements[1][0]


def fake_update_connection(monkeypatch, current=(3, None)):
    statements = []

    class Cursor:
        def execute(self, statement, params=None):
            statements.append((" ".join(statement.split()), params))

        def fetchone(self):
            return current

        def __enter__(self):
            return self

        def __exit__(self, *args):
            pass

    @contextmanager
    def connection():
        yield type("Connection", (), {"cursor": lambda self: Cursor()})()

    monkeypatch.setattr(learn_feedback, "_connection", connection)
    return statements


def test_patch_updates_same_row_and_only_updated_at(monkeypatch):
    statements = fake_update_connection(monkeypatch)
    feedback_id = uuid4()

    learn_feedback.update_feedback(feedback_id, rating=2, comment="Más ejemplos")

    assert len(statements) == 2
    update_sql, params = statements[1]
    assert "UPDATE learn.feedback" in update_sql
    assert "rating = %s" in update_sql and "comment = %s" in update_sql
    assert "updated_at = CURRENT_TIMESTAMP" in update_sql
    assert "created_at" not in update_sql
    assert "INSERT" not in update_sql
    assert params == [2, "Más ejemplos", feedback_id]


